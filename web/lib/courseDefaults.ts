// 學生端「選課規則與時間說明」沒有自訂內容時顯示的預設四條規則；老師管理頁的留空提示也用同一份，
// 這樣老師才看得到留空＝實際上會顯示的內容，不用自己猜。
export function defaultCourseRuleLines(teacherName: string): string[] {
  return [
    '平日晚上是熱門時段，選得越多越容易安排，但不保證排到第一志願',
    '送出不代表預約完成，請以正式課表為準',
    '時間都無法安排時，我們會另外與你聯絡',
    `虛線格子是 ${teacherName} 不上班的時段，可能會安排其他老師授課`,
  ];
}
